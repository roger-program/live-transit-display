"""Generate deterministic replay headers from checked-in synthetic/historical JSON."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

def outputs():
    items = []
    for path in sorted((ROOT / "fixtures").glob("*.json")):
        data = json.dumps(json.loads(path.read_text()), ensure_ascii=True, separators=(",", ":"))
        symbol = "FixtureJson" if path.stem == "feed-v1" else "StatesJson"
        items.append((symbol, data))
    return "#pragma once\n// Generated by tools/generate_fixtures.py; do not hand-edit.\n" + "\n".join(
        f'inline constexpr char {symbol}[] = R"FIXTURE({data})FIXTURE";' for symbol, data in items
    ) + "\n"

parser = argparse.ArgumentParser()
parser.add_argument("--check", action="store_true")
args = parser.parse_args()
target = ROOT / "include" / "fixture.h"
expected = outputs()
if args.check:
    if not target.exists() or target.read_text() != expected:
        raise SystemExit("Fixture header out of date: run python tools/generate_fixtures.py")
else:
    target.write_text(expected)
