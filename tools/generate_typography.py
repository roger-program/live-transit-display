"""Copy exact sibling browser bitmap masters; no font rasterizer/dependencies.

Run again after a deliberate browser-font change, then review the generated diff.
--check compares every mask plus source hashes without writing anything.
"""
import argparse
import hashlib
from pathlib import Path
import re
import subprocess

ROOT = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser()
parser.add_argument('--source', type=Path, default=ROOT.parent / 'live-transit-feed')
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
font_path = args.source / 'scripts/concept/identity/fonts.ts'
render_path = args.source / 'scripts/concept/render.ts'
fonts, render = font_path.read_text(), render_path.read_text()

def glyphs(section):
    entries = re.findall(r"(?:'([^']+)'|\b([A-Z])):\s*\[([\d,\s]+)\]", section)
    return [(quoted or bare, [int(n) for n in masks.split(',') if n.strip()])
            for quoted, bare, masks in entries]

lines = ['// Generated by tools/generate_typography.py. Do not edit bitmap masks.',
         '// Source: live-transit-feed/scripts/concept/identity/fonts.ts and concept/render.ts.',
         f'// fonts.ts SHA256: {hashlib.sha256(font_path.read_bytes()).hexdigest()}',
         f'// render.ts SHA256: {hashlib.sha256(render_path.read_bytes()).hexdigest()}',
         '#pragma once', '#include "font.h"', 'namespace typography {']
for table, start, end in [('Labels', 'export const FACES = {', '} satisfies'),
                          ('Countdowns', 'export const COUNTDOWNS = {', '\n};')]:
    section = fonts.split(start, 1)[1].split(end, 1)[0]
    for face in 'BCD':
        body = re.search(r'  ' + face + r': \{(.*?)\n  \}', section, re.S)
        if not body:
            raise SystemExit('Browser table shape changed; review importer')
        rows = glyphs(body.group(1))
        if len(rows) != (36 if table == 'Labels' else 10):
            raise SystemExit('Incomplete browser glyph table')
        lines.append(f'inline constexpr transit::Glyph {table}{face}[] = {{')
        for char, masks in rows:
            if len(masks) != 5 or any(n < 0 or n > 31 for n in masks):
                raise SystemExit('Invalid five-row glyph')
            lines.append("{'" + char + "', {" + ', '.join(map(str, masks)) + '}},')
        lines.append('};')
# Keep punctuation from the same compact concept, rather than inventing glyphs.
# Apostrophe is quoted differently in that TypeScript table; handle it explicitly.
body = render.split('const FONT:', 1)[1].split('\n};', 1)[0]
punctuation = [(char, masks) for char, masks in glyphs(body)
               if len(char) == 1 and not char.isalnum()]
punctuation.append(("'", [2, 2, 0, 0, 0]))
expected = set(" -./?':")
if set(char for char, _ in punctuation) != expected:
    raise SystemExit('Browser punctuation changed; review importer')
lines.append('inline constexpr transit::Glyph Punctuation[] = {')
for char, masks in punctuation:
    escaped = "\\'" if char == "'" else char
    lines.append("{'" + escaped + "', {" + ', '.join(map(str, masks)) + '}},')
lines += ['};', '} // namespace typography', '']
if "face === 'D' && 'CEFJLS'.includes(char)" not in fonts:
    raise SystemExit('Browser width policy changed; review diagnostic widths')
# Same formatter/version as the rest of this repository.
formatted = subprocess.run([str(ROOT / '.venv/bin/clang-format'),
                            f'--style=file:{ROOT / ".clang-format"}'],
                           input='\n'.join(lines), text=True, capture_output=True, check=True).stdout
output = ROOT / 'include/typography_glyphs.h'
if args.check:
    if output.read_text() != formatted:
        raise SystemExit('Typography snapshot differs from sibling browser sources')
    print('Typography masks, widths and source hashes match the browser snapshot')
else:
    output.write_text(formatted)
    print('Wrote include/typography_glyphs.h')
